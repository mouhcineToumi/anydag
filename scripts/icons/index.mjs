#!/usr/bin/env node
/**
 * `src/render/icon-index.ts`: which names the icon art holds, without the art.
 *
 * `iconFor()` decides what an `icon=` draws — a logo in its colours, a silhouette, a Lucide glyph —
 * synchronously, before anything is drawn, and it used to decide by looking the name up in the art
 * itself: `icons/data/icons.json` (2.5 MB) and every one of Lucide's glyphs, both static imports, so
 * a note page, the calendar and a board with no diagram on it all carried them. The art is a chunk
 * of its own now (`src/render/art.ts`), loaded the first time something draws one, and this is the
 * part the decision needs: four lists of names, about fifty kilobytes.
 *
 * Written by `build.mjs` after the bundle, runnable on its own (`node scripts/icons/index.mjs`), and
 * held to the bundle and to the installed `lucide-react` by `check-icons.mjs`.
 */
import { readFileSync, writeFileSync } from "node:fs";
import path from "node:path";
import { fileURLToPath } from "node:url";

const root = path.resolve(path.dirname(fileURLToPath(import.meta.url)), "../..");
export const INDEX_FILE = path.join(root, "src/render/icon-index.ts");

/** Lucide's glyphs by the name it exports them under — `KeyRound`, never `LucideKeyRound` or `KeyRoundIcon`. */
export async function lucideNames() {
  return Object.keys(await import("lucide-react"))
    .filter((k) => /^[A-Z]/.test(k) && !k.startsWith("Lucide") && !k.endsWith("Icon"))
    .sort();
}

/** The file's text, for the bundle at `icons/data/icons.json` and the installed Lucide. */
export async function renderIconIndex() {
  const bundle = JSON.parse(readFileSync(path.join(root, "icons/data/icons.json"), "utf8"));
  const set = (name, doc, names) =>
    `/** ${doc} */\nexport const ${name}: ReadonlySet<string> = new Set([\n${names.map((n) => `  ${JSON.stringify(n)},`).join("\n")}\n]);\n`;
  const aliases = Object.entries(bundle.aliases).sort(([a], [b]) => (a < b ? -1 : 1));
  return (
    `/* GENERATED by scripts/icons/index.mjs — do not edit. Run \`npm run icons:build\`. */\n\n` +
    set("COLOR", "The logos drawn in their own colours (`icons.json`'s `color`).", Object.keys(bundle.color).sort()) +
    "\n" +
    set("MONO", "The brands drawn as a silhouette in `currentColor` (`icons.json`'s `mono`).", Object.keys(bundle.mono).sort()) +
    "\n" +
    `/** The bundle's own indirection: \`pg\` is \`postgresql\`. */\nexport const ALIASES: Readonly<Record<string, string | undefined>> = {\n${aliases.map(([a, b]) => `  ${JSON.stringify(a)}: ${JSON.stringify(b)},`).join("\n")}\n};\n` +
    "\n" +
    set("LUCIDE", "Lucide's glyphs, by the name `lucide-react` exports them under.", await lucideNames())
  );
}

export async function writeIconIndex() {
  const text = await renderIconIndex();
  writeFileSync(INDEX_FILE, text);
  return text;
}

if (process.argv[1] && path.resolve(process.argv[1]) === fileURLToPath(import.meta.url)) {
  const text = await writeIconIndex();
  console.log(`src/render/icon-index.ts ${(text.length / 1024).toFixed(0)} KB`);
}
