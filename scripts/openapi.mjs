#!/usr/bin/env node
/**
 * The OpenAPI documents, generated from the code and checked against what is committed.
 *
 *     node scripts/openapi.mjs           write every spec's JSON and its Markdown reference
 *     node scripts/openapi.mjs --check   exit 1 if a committed file is not what the code generates
 *
 * `npm run openapi` is the first, `npm run check:openapi` (in `npm run checks`) the second.
 *
 * Load-bearing:
 * - **One list, one generator.** A spec is an entry of `SPECS`: the module that makes its document,
 *   the function that does, and the two files it is committed as. The local server's spec is one more
 *   entry; the builder (`api/openapi/document.ts`) and the renderer (`api/openapi/markdown.ts`)
 *   are shared.
 * - **The document comes from the module, never from a running server**: each entry is bundled with
 *   its packages left outside (as `check-skill.mjs` reads `TOOLS`) and imported, so the check needs
 *   no port, no database and no build of `dist/`.
 * - **A committed copy is the generated bytes or it is stale.** No normalising, no tolerance: the
 *   JSON is `JSON.stringify(doc, null, 2)` and a newline, and the reference is what the renderer
 *   wrote. A failure names the file and the command that fixes it.
 */
import fs from "node:fs";
import path from "node:path";
import { fileURLToPath, pathToFileURL } from "node:url";

const ROOT = path.resolve(path.dirname(fileURLToPath(import.meta.url)), "..");

/** Every published spec. `module` exports `make`, which takes nothing and answers the document. */
export const SPECS = [
  {
    name: "sync",
    module: "./api/server/openapi",
    make: "syncDocument",
    json: "docs/api/sync.openapi.json",
    reference: "docs/api/sync.md",
  },
  {
    name: "local",
    module: "./server/openapi",
    make: "localDocument",
    json: "docs/api/local.openapi.json",
    reference: "docs/api/local.md",
  },
];

/** Each spec's files and their contents, as the code makes them now. */
export async function generate() {
  const { build } = await import("esbuild");
  const files = new Map();
  for (const spec of SPECS) {
    const out = path.join(ROOT, "node_modules", ".cache", "openapi", `${spec.name}.mjs`);
    await build({
      absWorkingDir: ROOT,
      stdin: {
        contents: [
          `export { ${spec.make} as make } from ${JSON.stringify(spec.module)};`,
          'export { reference } from "./api/openapi/markdown";',
        ].join("\n"),
        resolveDir: ROOT,
        loader: "ts",
      },
      bundle: true,
      platform: "node",
      format: "esm",
      packages: "external",
      outfile: out,
      logLevel: "warning",
    });
    const mod = await import(`${pathToFileURL(out).href}?t=${Date.now()}`);
    const doc = mod.make();
    files.set(spec.json, `${JSON.stringify(doc, null, 2)}\n`);
    files.set(spec.reference, mod.reference(doc, path.basename(spec.json)));
  }
  return files;
}

async function main() {
  const check = process.argv.includes("--check");
  const files = await generate();
  const stale = [];
  for (const [rel, text] of files) {
    const file = path.join(ROOT, rel);
    const had = fs.existsSync(file) ? fs.readFileSync(file, "utf8") : null;
    if (had === text) continue;
    if (check) stale.push(rel);
    else {
      fs.mkdirSync(path.dirname(file), { recursive: true });
      fs.writeFileSync(file, text);
      console.log(`wrote ${rel}`);
    }
  }
  if (stale.length) {
    console.error(
      `check:openapi: ${stale.join(", ")} ${stale.length === 1 ? "is" : "are"} not what the code generates — run \`npm run openapi\` and commit the result`,
    );
    process.exit(1);
  }
  if (check) console.log(`check:openapi: ${files.size} files match the code`);
}

if (process.argv[1] && fileURLToPath(import.meta.url) === path.resolve(process.argv[1])) await main();
