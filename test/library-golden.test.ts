import fs from "node:fs";
import path from "node:path";
import { fileURLToPath } from "node:url";
import { describe, expect, it } from "vitest";

import { appendPart, isFragment, LIBRARY, render } from "@/board/library";
import { TEMPLATES } from "@/board/templates";
import { isDiagramType } from "@/board/types";

/**
 * Every component's rendered text, frozen.
 *
 * The library was a flat list of hand-written strings before it was a composition of atoms, and the
 * only thing that can prove the decomposition changed no output is the output itself. So this
 * writes what every blueprint renders to — keyed by id, so a new component is a pure addition and a
 * changed one is a diff on the line that owns it.
 *
 * It outlives the refactor that motivated it: an atom is shared by everything above it, so editing
 * one is a change to a dozen composites at once, and this is where that shows up as something to
 * read rather than something to discover.
 *
 * `UPDATE_GOLDEN=1 npx vitest run test/library-golden.test.ts` rewrites it. Read the diff.
 */

const FILE = path.resolve(path.dirname(fileURLToPath(import.meta.url)), "__golden__/library.txt");

/** A part is rendered alone and appended twice, which is what freezes the id numbering. */
function dump(): string {
  const out: string[] = [];
  /* The pictures are fifteen hundred entries of one statement shape, generated by one
     function over the emoji set — so they are frozen one line each, in shelf order, rather than as
     fifteen hundred copies of the Wireframe starter with a figure appended twice. What can change
     about one is its id, its shelf, its name and the text it writes, and a line holds all four. */
  const objects = LIBRARY.filter((c) => c.shelf);
  for (const c of [...LIBRARY].filter((c) => !c.shelf).sort((a, b) => a.id.localeCompare(b.id))) {
    const attrs = Object.entries(c.attrs ?? {})
      .map(([k, v]) => `${k}=${String(v)}`)
      .join(" ");
    out.push(`## ${c.id}`);
    out.push(`type: ${c.type}  icon: ${c.icon}${attrs ? `  attrs: ${attrs}` : ""}`);
    out.push(`name: ${c.name}`);
    out.push(`desc: ${c.description}`);
    out.push("--- alone");
    out.push(render(c));
    if (isFragment(c) && isDiagramType(c.type)) {
      const once = appendPart(c, TEMPLATES[c.type]);
      out.push("--- appended twice to its template");
      out.push(appendPart(c, once));
    }
    out.push("");
  }
  out.push("## objects — id · shelf · the text it writes alone");
  for (const c of objects) out.push(`${c.id} · ${c.shelf} · ${render(c)}`);
  return `${out.join("\n").replace(/\s+$/, "")}\n`;
}

describe("the library's rendered text", () => {
  it("matches the golden", () => {
    const got = dump();
    if (process.env.UPDATE_GOLDEN === "1") {
      fs.writeFileSync(FILE, got);
      return;
    }
    expect(fs.existsSync(FILE), `${FILE} is missing — run with UPDATE_GOLDEN=1`).toBe(true);
    expect(got).toBe(fs.readFileSync(FILE, "utf8"));
  });
});
